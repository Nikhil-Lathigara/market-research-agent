import json
import os
import time
from datetime import datetime, timezone
from pathlib import Path

from crewai import Agent, Crew, LLM, Process, Task
from dotenv import load_dotenv

from tools.prompt_loader import load_prompt_config
from tools.usage_tracker import record_agent_usage

load_dotenv()

# --------------------------------------------------
# 1. Configuration
# --------------------------------------------------

BASE_DIR = Path(__file__).resolve().parent
OUTPUT_DIR = BASE_DIR / "outputs"

INPUT_FILE = OUTPUT_DIR / "research_evidence.json"
OUTPUT_FILE = OUTPUT_DIR / "analysis_report.json"
RAW_OUTPUT_FILE = OUTPUT_DIR / "analysis_raw.txt"

OUTPUT_DIR.mkdir(exist_ok=True)

api_key = os.getenv("GEMINI_API_KEY")

if not api_key:
    raise ValueError("GEMINI_API_KEY is missing from .env")

if not INPUT_FILE.exists():
    raise FileNotFoundError(
        f"Research file not found: {INPUT_FILE}. "
        "Run main.py first."
    )

research_data = json.loads(
    INPUT_FILE.read_text(encoding="utf-8")
)

research_json = json.dumps(
    research_data,
    ensure_ascii=False,
    indent=2,
)

llm = LLM(
    model="gemini/gemini-3.5-flash-lite",
    api_key=api_key,
    temperature=0.2,
)

# --------------------------------------------------
# 2. Analyst Agent & Task from prompts/analyst.yaml
# --------------------------------------------------

prompt_cfg = load_prompt_config("analyst")

analyst_agent = Agent(
    role=prompt_cfg["agent"]["role"],
    goal=prompt_cfg["agent"]["goal"],
    backstory=prompt_cfg["agent"]["backstory"],
    llm=llm,
    verbose=True,
    allow_delegation=False,
    max_iter=8,
)

analysis_task = Task(
    description=prompt_cfg["task"]["description"],
    expected_output=prompt_cfg["task"]["expected_output"],
    agent=analyst_agent,
)

def validate_evidence_references(report, research):
    valid_ids = {
        item["evidence_id"]
        for item in research.get("evidence", [])
        if item.get("evidence_id")
    }

    referenced_ids = set()

    def collect_ids(value):
        if isinstance(value, dict):
            for key, item in value.items():
                if key == "evidence_ids" and isinstance(item, list):
                    referenced_ids.update(item)
                else:
                    collect_ids(item)

        elif isinstance(value, list):
            for item in value:
                collect_ids(item)

    collect_ids(report)

    invalid_ids = referenced_ids - valid_ids

    if invalid_ids:
        raise ValueError(
            f"Invalid evidence IDs: {sorted(invalid_ids)}"
        )

    print(f"Valid evidence IDs: {len(referenced_ids)}")
    print("Invalid evidence IDs: 0")

# --------------------------------------------------
# 4. Execute analysis
# --------------------------------------------------

start_time = time.perf_counter()

crew = Crew(
    agents=[analyst_agent],
    tasks=[analysis_task],
    process=Process.sequential,
    verbose=True,
)

result = crew.kickoff(
    inputs={"research_data": research_json}
)

duration_seconds = round(
    time.perf_counter() - start_time,
    2,
)

record_agent_usage(
    agent_name="Analyst Agent",
    model_name=llm.model,
    crew_output=result,
    duration_seconds=duration_seconds,
)

raw_output = str(result).strip()
json_text = raw_output

# Handle accidental Markdown fences.
if json_text.startswith("```"):
    lines = json_text.splitlines()

    if lines and lines[0].startswith("```"):
        lines = lines[1:]

    if lines and lines[-1].strip() == "```":
        lines = lines[:-1]

    json_text = "\n".join(lines).strip()

# --------------------------------------------------
# 5. Save analysis
# --------------------------------------------------

try:
    report = json.loads(json_text)
    
    validate_evidence_references(report, research_data)

    # Generate one authoritative timestamp for this run.
    generated_at = datetime.now(timezone.utc).isoformat()

    # Do not trust the timestamp generated by the LLM.
    report["analysis_timestamp"] = generated_at

    report["run_metadata"] = {
        "generated_at": generated_at,
        "duration_seconds": duration_seconds,
        "model": "gemini/gemini-3.5-flash-lite",
        "input_file": str(INPUT_FILE),
    }
    OUTPUT_FILE.write_text(
        json.dumps(
            report,
            indent=2,
            ensure_ascii=False,
        ),
        encoding="utf-8",
    )

    print(f"\nAnalysis saved to: {OUTPUT_FILE}")

except json.JSONDecodeError:
    RAW_OUTPUT_FILE.write_text(
        raw_output,
        encoding="utf-8",
    )

    print("\nThe model did not return valid JSON.")
    print(f"Raw output saved to: {RAW_OUTPUT_FILE}")

print(f"Analysis duration: {duration_seconds} seconds")
print("Analyst Agent finished.")